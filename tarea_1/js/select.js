const data_tipo = ["Paseiforme (pájaros)", "Rapaz (aves de presa)", "Anseriforme (aves acuaticas)", "Corredoras", "Otro"]

const data_orden = ["Ave (A-Z)", "Ave (Z-A)", "Tipo (A-Z)", "Tipo (Z-A)", "Región (A-Z)", "Región (Z-A)", "Fecha (más reciente)", "Fecha (menos reciente)"];

const poblarRegiones = () => {
    let regionSelect = document.getElementById("select-region");
    for (const region in data_regiones) {
      let option = document.createElement("option");
      option.value = region;
      option.text = region;
      regionSelect.appendChild(option);
    }
    
  };


const updateComunas = () => {
    let regionSelect = document.getElementById("select-region");
    let comunaSelect = document.getElementById("select-comuna");
    
    let selectedRegion = regionSelect.value;
    
    comunaSelect.innerHTML = "";
    
    if (data_regiones[selectedRegion]) {
      data_regiones[selectedRegion].forEach(comuna => {
        let option = document.createElement("option");
        option.value = comuna;
        option.text = comuna;
        comunaSelect.appendChild(option);
      });
    }
  };
  
const poblarTipo = (idSelect, incluirOpcionTodos = false) => {
    let tipoSelect = document.getElementById(idSelect);
    if (!tipoSelect) return;

    if (incluirOpcionTodos) {
        let optionTodos = document.createElement("option");
        optionTodos.value = "";
        optionTodos.text = "Todos";
        tipoSelect.appendChild(optionTodos);
    }

    data_tipo.forEach(tipo => {
        let option = document.createElement("option");
        option.value = tipo;
        option.text = tipo;
        tipoSelect.appendChild(option);
    });
};

const poblarOrden = () => {
    let ordenarSelect = document.getElementById("ordenar-por");
    if (!ordenarSelect) return;

    data_orden.forEach(orden => {
        let option = document.createElement("option");
        option.value = orden;
        option.text = orden;
        ordenarSelect.appendChild(option);
    });
};

document.getElementById("select-region").addEventListener("change", updateComunas);

window.onload = () => {
  poblarRegiones();
  poblarTipo("select-tipo");
  poblarTipo("filtro-tipo");
  poblarOrden();
};